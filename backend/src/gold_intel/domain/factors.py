from typing import Literal

EpistemicStatus = Literal["OBSERVED", "CALCULATED", "INFERRED", "UNKNOWN"]
ImplementationStatus = Literal["ACTIVE", "PARTIAL", "CONTRACT", "LICENSED_INTERFACE"]
DependencyMode = Literal["ALL", "ANY"]

FACTOR_REGISTRY_VERSION = "gold-reference-book-2026-07-v8"


@dataclass(frozen=True, slots=True)
class FactorDefinition:
    code: str
    name: str
    domain: str
    layer: int | None
    epistemic_status: EpistemicStatus
    implementation_status: ImplementationStatus
    phase1_required: bool
    source_class: str
    series_codes: tuple[str, ...] = ()
    dependencies: tuple[str, ...] = ()
    dependency_mode: DependencyMode = "ALL"
    freshness_seconds: int | None = None
    note: str = ""


def _factor(
    code: str,
    name: str,
    domain: str,
    layer: int | None,
    epistemic_status: EpistemicStatus,
    implementation_status: ImplementationStatus,
    phase1_required: bool,
    source_class: str,
    *,
    series_codes: tuple[str, ...] = (),
    dependencies: tuple[str, ...] = (),
    dependency_mode: DependencyMode = "ALL",
    freshness_seconds: int | None = None,
    note: str = "",
) -> FactorDefinition:
    return FactorDefinition(
        code=code,
        name=name,
        domain=domain,
        layer=layer,
        epistemic_status=epistemic_status,
        implementation_status=implementation_status,
        phase1_required=phase1_required,
        source_class=source_class,
        series_codes=series_codes,
        dependencies=dependencies,
        dependency_mode=dependency_mode,
        freshness_seconds=freshness_seconds,
        note=note,
    )



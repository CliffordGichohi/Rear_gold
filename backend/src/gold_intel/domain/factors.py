def registry_hash() -> str:
    payload = json.dumps(
        [asdict(factor) for factor in FACTOR_REGISTRY],
        sort_keys=True,
        separators=(",", ":"),
    )
    return hashlib.sha256(payload.encode("utf-8")).hexdigest()
